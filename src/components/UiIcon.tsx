/**
 * An interface picture named in data (Help, empty screens). Decorative: the words beside it say
 * what it is, so it is hidden from screen readers. `kind` 'feature' for the big ones.
 */
export function UiIcon({ name, size = 20, kind = 'ui', className }: { name: UiIconName; size?: number; kind?: IconRole; className?: string }) {
  const weight = useIconWeight(kind)
  const Glyph = ICONS[name]
  return <Glyph size={size} weight={weight} className={className} aria-hidden data-icon={name} />
}
